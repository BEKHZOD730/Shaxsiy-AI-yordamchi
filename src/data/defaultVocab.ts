export const findDictionaryWord = (input: string): Omit<VocabWord, 'id' | 'audioPlayedCount' | 'createdAt' | 'status'> | null => {
  const normalized = input.trim().toLowerCase();
  if (EXPANDED_DICTIONARY_DB[normalized]) {
    return EXPANDED_DICTIONARY_DB[normalized];
  }

  // Substring / fuzzy search in keys
  const matchKey = Object.keys(EXPANDED_DICTIONARY_DB).find(k => k.includes(normalized) || normalized.includes(k));
  if (matchKey) {
    return EXPANDED_DICTIONARY_DB[matchKey];
  }

  return null;
};

